export interface Candle {
  time: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
  ema20?: number;
  sma50?: number;
  vwap?: number;
}

export function generateCandles(basePrice: number, count: number = 60, _timeframe: string = '15m'): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * 0.96;
  const now = new Date();
  
  for (let i = count; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = `${time.getHours().toString().padStart(2, '0')}:${time.getMinutes().toString().padStart(2, '0')}`;
    
    const volatility = basePrice * 0.0035;
    const change = (Math.sin(i * 0.5) * 0.5 + (Math.random() - 0.48)) * volatility;
    const open = currentPrice;
    const close = +(open + change).toFixed(2);
    const high = +(Math.max(open, close) + Math.random() * volatility * 0.7).toFixed(2);
    const low = +(Math.min(open, close) - Math.random() * volatility * 0.7).toFixed(2);
    const volume = Math.floor(25000 + Math.random() * 85000 + (Math.abs(change) / volatility) * 45000);
    
    currentPrice = close;
    
    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
      ema20: +(close * 0.995 + Math.sin(i) * 2).toFixed(2),
      sma50: +(close * 0.990 + Math.cos(i) * 3).toFixed(2),
      vwap: +((high + low + close) / 3 * 0.998).toFixed(2),
    });
  }
  
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }
  
  return candles;
}

export function getOptionChainForSymbol(symbol: string, basePrice: number, expiry: string = '28 AUG 2026'): OptionContract[] {
  if (symbol.toUpperCase().includes('NIFTY') && !symbol.toUpperCase().includes('BANK')) {
    return NIFTY_OPTION_CHAIN;
  }

  let strikeStep = 50;
  if (basePrice < 500) strikeStep = 10;
  else if (basePrice < 1500) strikeStep = 20;
  else if (basePrice < 3000) strikeStep = 50;
  else if (basePrice < 10000) strikeStep = 100;
  else strikeStep = 500;

  const atmStrike = Math.round(basePrice / strikeStep) * strikeStep;
  const strikes: number[] = [];
  for (let i = -3; i <= 3; i++) {
    strikes.push(atmStrike + i * strikeStep);
  }

  return strikes.map(strike => {
    const diff = strike - basePrice;
    
    const callIntrinsic = Math.max(0, basePrice - strike);
    const putIntrinsic = Math.max(0, strike - basePrice);
    const timeValue = Math.max(8, +(basePrice * 0.022 - Math.abs(diff) * 0.08).toFixed(2));
    
    const callLtp = +(callIntrinsic + timeValue).toFixed(2);
    const putLtp = +(putIntrinsic + timeValue * 0.95).toFixed(2);
    
    const callChg = +( (basePrice - strike) * 0.4 + (Math.random() * 5 - 2) ).toFixed(2);
    const putChg = +( (strike - basePrice) * 0.4 + (Math.random() * 5 - 2) ).toFixed(2);

    const callOi = Math.floor((3000000 + Math.random() * 5000000) / (1 + Math.abs(diff) / (strikeStep * 2)));
    const putOi = Math.floor((3000000 + Math.random() * 5000000) / (1 + Math.abs(diff) / (strikeStep * 2)));

    return {
      strike,
      expiry,
      call: {
        symbol: `${symbol}26AUG${strike}CE`,
        ltp: callLtp,
        change: callChg,
        changePercent: +((callChg / (callLtp - callChg || 1)) * 100).toFixed(1),
        bid: +(callLtp * 0.995).toFixed(2),
        ask: +(callLtp * 1.005).toFixed(2),
        iv: +(14.2 + (Math.random() * 2 - 1)).toFixed(1),
        volume: Math.floor(callOi * 0.45),
        oi: callOi,
        oiChange: Math.floor((Math.random() - 0.3) * 600000)
      },
      put: {
        symbol: `${symbol}26AUG${strike}PE`,
        ltp: putLtp,
        change: putChg,
        changePercent: +((putChg / (putLtp - putChg || 1)) * 100).toFixed(1),
        bid: +(putLtp * 0.995).toFixed(2),
        ask: +(putLtp * 1.005).toFixed(2),
        iv: +(15.1 + (Math.random() * 2 - 1)).toFixed(1),
        volume: Math.floor(putOi * 0.42),
        oi: putOi,
        oiChange: Math.floor((Math.random() - 0.3) * 600000)
      }
    };
  });
}
